export function buildDiagnosisSubjectCoverageRules(subjects: string[]): string {
  const filledSubjects = [...new Set(subjects.map((subject) => subject.trim()).filter(Boolean))];
  const subjectList = filledSubjects.join('、') || '未提供';
  const subjectCount = filledSubjects.length;

  if (subjectCount <= 1) {
    return `【本次科目覆盖规则：单科诊断】
- 已填写科目：${subjectList}。
- 第1节必须浓缩该科的水平、最大卡点、最近风险、未来7天核心动作和洋葱承接，写成顾问可直接照读的总结话术。
- 第2节输出该科3个家长可观察现象；第3节只保留该科2个最关键问题，每个问题都要写清根因和家长验证方法。
- 第5节输出该科量化危机链；第6节按三个周期输出行动方案；第7.1节逐项承接该科问题。
- 禁止生成任何未填写科目的具体问题。`;
  }

  return `【本次科目覆盖规则：${subjectCount}科诊断】
- 已填写科目：${subjectList}。以下每个科目都必须完整出现，禁止只分析最低分科目，禁止合并成总共3个问题。
- 第1节必须提到每个已填科目的核心判断；科目较多时每科只保留一个最需要家长知道的结论。
- 第2节必须按“### 科目名”分组，每科输出2-3个家长可观察现象。
- 第3节必须按“### 科目名”分组，每科保留1-2个最关键问题；每个问题写清专业判断、大白话根因和家长验证方法。
- 第5节必须逐科给出量化危机，再汇总多科对总分、作业时间和学习节奏的叠加影响。
- 第6节的三个周期必须覆盖每个已填科目；7天讲具体动作，1个月讲周节奏，当前学期讲阶段目标，三者禁止重复。
- 第7.1节每个科目至少1行产品承接，必须包含孩子的问题、使用功能、怎么用、为什么有效和老师怎么讲；不得限制为总共3行。
- 禁止生成任何未填写科目的具体问题，禁止为了控制篇幅删掉已填写科目。`;
}

